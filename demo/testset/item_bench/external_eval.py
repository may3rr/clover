"""Support judging on two public citation-accuracy datasets.

    python external_eval.py ci [--limit N]      # Citation-Integrity test set
    python external_eval.py sc [--sample N]     # SemanticCite, stratified sample
    python external_eval.py score ci|sc         # metrics of the last run
    python external_eval.py retrieval           # excerpt recall of the
                                                # human-marked evidence

Data is expected under runs/external/ (not committed):

- Citation-Integrity (Sarol et al., Bioinformatics 2024, MIT): 606 test
  citances with human labels; the cited article's paragraphs are in
  corpus.jsonl. Gold: ACCURATE, NOT_ACCURATE (every error subtype) or NEI
  (no evidence sentence, i.e. irrelevant), as in the paper. Our pipeline
  runs end to end: excerpt retrieval over the full article (BM25 fused
  with embeddings when enabled), first pass, detail check, review on a
  wider excerpt.
- SemanticCite (Haan 2025, CC-BY-NC): claim, three retrieved snippets and
  the reference metadata; labels were generated by GPT-4.1. We judge on
  the given snippets only, so this measures agreement with GPT-4.1.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import random
import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "backend"))

from citecheck.schema import Claim  # noqa: E402
from citecheck.support.judge import search_terms  # noqa: E402
from citecheck.support.layer import evaluate_with_excerpt  # noqa: E402
from citecheck.support.sources import _bm25_excerpt  # noqa: E402

EXT = HERE / "runs" / "external"
_MARK = re.compile(r"\(?<\|(?:multi_)?cit\|>\)?")


def _ci_items(limit: int | None):
    corpus = {}
    for line in open(EXT / "citation_integrity" / "corpus.jsonl", encoding="utf-8"):
        d = json.loads(line)
        corpus[d["doc_id"]] = d
    out = []
    for line in open(EXT / "citation_integrity" / "claims-test.jsonl", encoding="utf-8"):
        c = json.loads(line)
        labels = {e["label"] for v in c["evidence"].values() for e in v}
        gold = ("NEI" if not labels or labels == {"IRRELEVANT"}
                else "ACCURATE" if labels == {"ACCURATE"} else "NOT_ACCURATE")
        paras = [" ".join(corpus[i]["abstract"]) for i in sorted(c["cited_doc_ids"]) if i in corpus]
        claim = _MARK.sub("", c["claim"]).strip()
        out.append({"id": f"ci{c['id']}", "claim": claim, "gold": gold,
                    "multi": "<|multi_cit|>" in c["claim"],
                    "title": paras[0][:200] if paras else None,
                    "body": "\n\n".join(paras)})
    return out[:limit] if limit else out


def _sc_items(sample: int):
    data = json.load(open(EXT / "semanticcite" / "SemanticCite_dataset.json", encoding="utf-8"))
    rnd = random.Random(0)
    by = {}
    for i, d in enumerate(data):
        by.setdefault(d["output"]["classification"], []).append((i, d))
    picked = []
    for lab, rows in sorted(by.items()):
        k = round(sample * len(rows) / len(data))
        picked += rnd.sample(rows, min(k, len(rows)))
    out = []
    for i, d in sorted(picked, key=lambda x: x[0]):
        meta = d["input"]["ref_metadata"]
        title = re.search(r"Title:\s*(.+)", meta)
        snippets = "\n\n".join(s["text"] for s in d["input"]["ref_snippets"])
        out.append({"id": f"sc{i}", "claim": d["input"]["claim"],
                    "gold": d["output"]["classification"],
                    "title": title.group(1).strip() if title else None,
                    "excerpt": f"{meta.strip()}\n\n{snippets}"})
    return out


async def _judge(it: dict, kind: str, sem) -> dict:
    async with sem:
        claim = Claim(id=it["id"], paragraph_id="p0", start=0, end=len(it["claim"]),
                      text=it["claim"], marker_ids=["m0"])
        expand = None
        if kind == "ci":
            terms = await search_terms(it["claim"])
            query = " ".join([it["claim"], *terms])
            excerpt = await asyncio.to_thread(_bm25_excerpt, it["body"], query, 2500, 600)

            def expand(q, body=it["body"]):
                return _bm25_excerpt(body, q, 6000, head=600, max_parts=12)
        else:
            excerpt = it["excerpt"]
        chk = await evaluate_with_excerpt(claim, "r1", excerpt, it["title"], "fulltext",
                                          expand=expand)
        return {"id": it["id"], "gold": it["gold"], "label": chk.label,
                "off_topic": chk.off_topic, "evidence": chk.evidence,
                "rationale": chk.rationale, "multi": it.get("multi", False)}


async def run(kind: str, limit: int | None, sample: int, concurrency: int) -> None:
    items = _ci_items(limit) if kind == "ci" else _sc_items(sample)
    sem = asyncio.Semaphore(concurrency)
    rows = await asyncio.gather(*(_judge(it, kind, sem) for it in items))
    out = EXT / f"{kind}_run.jsonl"
    out.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), "utf-8")
    print(f"{len(rows)} items -> {out}")
    score(kind)


def _f1(rows, labels, pred_of):
    out = {}
    for lab in labels:
        tp = sum(1 for r in rows if pred_of(r) == lab and r["gold"] == lab)
        p = sum(1 for r in rows if pred_of(r) == lab)
        g = sum(1 for r in rows if r["gold"] == lab)
        prec, rec = (tp / p if p else 0.0), (tp / g if g else 0.0)
        out[lab] = (2 * prec * rec / (prec + rec) if prec + rec else 0.0, prec, rec, g)
    return out


def score(kind: str) -> None:
    rows = [json.loads(ln) for ln in (EXT / f"{kind}_run.jsonl").read_text("utf-8").split("\n") if ln.strip()]
    n = len(rows)
    flagged = lambda r: r["label"] in ("partial", "unsupported") or r["off_topic"]  # noqa: E731
    if kind == "ci":
        def pred(r):
            if r["off_topic"]:
                return "NEI"
            return {"supported": "ACCURATE", "partial": "NOT_ACCURATE",
                    "unsupported": "NOT_ACCURATE"}.get(r["label"], "NEI")
        labels = ["ACCURATE", "NOT_ACCURATE", "NEI"]
        problem = lambda r: r["gold"] != "ACCURATE"  # noqa: E731
    else:
        def pred(r):
            return {"supported": "SUPPORTED", "partial": "PARTIALLY_SUPPORTED",
                    "unsupported": "UNSUPPORTED"}.get(r["label"], "UNCERTAIN")
        labels = ["SUPPORTED", "PARTIALLY_SUPPORTED", "UNSUPPORTED", "UNCERTAIN"]
        problem = lambda r: r["gold"] in ("PARTIALLY_SUPPORTED", "UNSUPPORTED")  # noqa: E731
    acc = sum(pred(r) == r["gold"] for r in rows) / n
    f1 = _f1(rows, labels, pred)
    macro = sum(v[0] for v in f1.values()) / len(labels)
    print(f"{kind}: {n} 条，标准准确率 {acc:.3f}，macro-F1 {macro:.3f}")
    print("| 类别 | 金标条数 | F1 | 查准 | 查全 |")
    for lab, (f, p, r_, g) in f1.items():
        print(f"| {lab} | {g} | {f:.2f} | {p:.2f} | {r_:.2f} |")
    tp = sum(1 for r in rows if flagged(r) and problem(r))
    fp = sum(1 for r in rows if flagged(r) and not problem(r))
    fn = sum(1 for r in rows if not flagged(r) and problem(r))
    print(f"报警 {tp + fp} 条，报警准确率 {tp / max(tp + fp, 1):.2f}，有问题的引用查出 {tp}/{tp + fn} = {tp / max(tp + fn, 1):.2f}")
    print("预测分布", Counter(pred(r) for r in rows), "金标分布", Counter(r["gold"] for r in rows))
    if kind == "ci":
        cm = Counter((r["gold"], pred(r)) for r in rows)
        print("混淆矩阵 金标→预测", dict(cm))


async def retrieval() -> None:
    """Does the excerpt hold a human-marked evidence sentence? Citation-
    Integrity marks evidence sentences in the cited article for ACCURATE
    and NOT_ACCURATE citances; a hit is any one of them inside the excerpt."""
    from citecheck.config import get_settings
    from citecheck.support.evidence import normalize_text

    corpus = {}
    for line in open(EXT / "citation_integrity" / "corpus.jsonl", encoding="utf-8"):
        d = json.loads(line)
        corpus[d["doc_id"]] = d
    items = []
    for line in open(EXT / "citation_integrity" / "claims-test.jsonl", encoding="utf-8"):
        c = json.loads(line)
        gold = [corpus[int(doc)]["abstract"][i] for doc, evs in c["evidence"].items()
                for e in evs if e["label"] != "IRRELEVANT" for i in e["sentences"]
                if int(doc) in corpus]
        if not gold:
            continue
        paras = [" ".join(corpus[i]["abstract"]) for i in sorted(c["cited_doc_ids"]) if i in corpus]
        claim = _MARK.sub("", c["claim"]).strip()
        terms = await search_terms(claim)
        items.append((" ".join([claim, *terms]), "\n\n".join(paras),
                      [normalize_text(g)[:80] for g in gold]))
    rr = get_settings().llm.rerank
    methods = [("BM25", False, None), ("BM25 与向量融合", True, None),
               ("融合加重排 0.6B", True, "Qwen/Qwen3-Reranker-0.6B"),
               ("融合加重排 4B", True, "Qwen/Qwen3-Reranker-4B")]
    print(f"有人工证据句的引用 {len(items)} 条")
    print("| 方法 | 首轮 2500 字 | 复核 6000 字 |")
    print("| --- | --- | --- |")
    for name, dense, model in methods:
        rr.enabled = model is not None
        if model:
            rr.model = model
        cells = []
        for budget, parts in ((2500, 5), (6000, 12)):
            def hit(it):
                ex = normalize_text(_bm25_excerpt(it[1], it[0], budget, head=600,
                                                  max_parts=parts, dense=dense))
                return any(g in ex for g in it[2])
            hits = sum(await asyncio.gather(*(asyncio.to_thread(hit, it) for it in items)))
            cells.append(f"{hits}/{len(items)} = {hits / len(items):.2f}")
        print(f"| {name} | " + " | ".join(cells) + " |")


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("ci")
    c.add_argument("--limit", type=int)
    c.add_argument("--concurrency", type=int, default=16)
    s = sub.add_parser("sc")
    s.add_argument("--sample", type=int, default=400)
    s.add_argument("--concurrency", type=int, default=16)
    sub.add_parser("retrieval")
    sc = sub.add_parser("score")
    sc.add_argument("kind", choices=("ci", "sc"))
    args = ap.parse_args()
    if args.cmd == "score":
        score(args.kind)
    elif args.cmd == "retrieval":
        asyncio.run(retrieval())
    else:
        asyncio.run(run(args.cmd, getattr(args, "limit", None), getattr(args, "sample", 400),
                        args.concurrency))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
